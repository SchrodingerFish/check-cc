export function localizeLocation(value: string, locale: LocaleCode) {
  if (locale !== "ru") return value;
  return value
    .replace(/日本/g, "Япония")
    .replace(/东京都/g, "Токио")
    .replace(/东京/g, "Токио")
    .replace(/中国大陆/g, "материковый Китай")
    .replace(/中国/g, "Китай");
}

